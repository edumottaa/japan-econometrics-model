args<-commandArgs(trailingOnly=TRUE)
source("C:/Users/dudup/OneDrive/japan-econometrics-model/src/evaluation/avaliacao_plano/common.R")
out<-args[1];p<-as.integer(args[2]);cfg<-readRDS(file.path(out,"config.rds"));d<-readRDS(file.path(out,"data_frozen.rds"));paths<-readRDS(file.path(out,"external_paths.rds"))
check_package_protocol(cfg)
for(i in seq_along(cfg$origins)){
 file<-file.path(out,"windows",sprintf("native_p%d_w%03d.rds",p,i));if(file.exists(file))next
 write_status(file.path(out,"status",paste0("native_p",p,".json")),state="running",fold=i,lag=p,pid=Sys.getpid())
 n<-cfg$origins[i];train<-d |> slice_head(n=n);test<-d |> slice((n+1):min(n+24,nrow(d)));Y<-as.matrix(select(as_tibble(train),all_of(vars)))
 start<-Sys.time();warnings_seen<-character();log_line("native H24",p,"INICIO",i)
 res<-tryCatch(withCallingHandlers({
  set.seed(cfg$seed+i)
  pr<-bv_priors(hyper=cfg$bvar_hyper,mn=bv_minnesota(lambda=bv_lambda(),psi=bv_psi()),soc=bv_soc(),sur=bv_sur(min=.001))
  mh<-bv_mh(adjust_acc=TRUE,acc_lower=.2,acc_upper=.4,acc_change=.1)
  fit<-BVAR::bvar(Y,lags=p,n_draw=5000,n_burn=2500,n_thin=1,priors=pr,mh=mh,verbose=FALSE)
  di<-diagnostico_bvar(fit,p,i)
  set.seed(300000+i);F<-aperm(stats::predict(fit,horizon=24)$fcast,c(3,2,1))
  sc<-score_full_draws(F,train,test,i,paste0("BVAR_normal_p",p),di$quality)
  normal_samples<-F[5:10,,,drop=FALSE];rm(F)
  set.seed(400000+i);fc<-predict(fit,horizon=24,cond_path=paths[[i]],cond_vars=colnames(paths[[i]]))
  err<-max(vapply(seq_len(ncol(paths[[i]])),function(j){k<-match(colnames(paths[[i]])[j],fit$variables);max(abs(sweep(fc$fcast[,,k],2,paths[[i]][,j],"-")))},numeric(1)))
  stopifnot(err<1e-6)
  F<-aperm(fc$fcast,c(3,2,1));sc<-bind_rows(sc,score_full_draws(F,train,test,i,paste0("BVAR_condicionado_p",p),di$quality))
  list(scores24=sc,diagnostic=di,forecasts24=list(normal=normal_samples,conditional=F[5:10,,,drop=FALSE]),forecast_variables=alvos,error=NULL)
 },warning=function(w){warnings_seen<<-c(warnings_seen,conditionMessage(w));invokeRestart("muffleWarning")}),error=function(e)list(error=conditionMessage(e),diagnostic=tibble(family="BVAR",p=p,fold=i,quality="execution_failure")))
 res$warnings<-unique(warnings_seen);res$elapsed_seconds<-as.numeric(difftime(Sys.time(),start,units="secs"));res$origin<-max(train$date);saveRDS(res,file,compress=TRUE)
 log_line("native H24",p,"FIM",i,"segundos",round(res$elapsed_seconds,1),"erro",if(is.null(res$error))"nenhum" else res$error)
 rm(res);if(exists("fit"))rm(fit);if(exists("fc"))rm(fc);if(exists("F"))rm(F);if(exists("normal_samples"))rm(normal_samples);gc(verbose=FALSE)
}
write_status(file.path(out,"status",paste0("native_p",p,".json")),state="complete",completed=47,lag=p,pid=Sys.getpid())
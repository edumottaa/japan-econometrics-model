out<-file.path(root,"data/processed/investigacao_foreign_20261018")
old_dir<-file.path(root,"data/processed/cv_comparacao_20261017_193604")
d<-readRDS(file.path(old_dir,"data_frozen.rds"));cfg<-readRDS(file.path(old_dir,"config.rds"));rows<-list()
for(i in c(26L,27L)){
 Y<-as.matrix(as_tibble(d)[1:cfg$origins[i],vars]);sp<-specify_bsvarSIGN$new(data=Y[,5:10],foreign=Y[,1:4],p=6,hyper_mu=FALSE,hyper_delta=FALSE,hyper_lambda=FALSE,hyper_psi=FALSE)
 pr<-sp$prior$get_prior();h<-pr$hyper[,1];psi<-h[4:13]
 pm<-diag(diag(pr$V)*c(rep(h[3]^2/psi,6),1))
 Ym<-rbind(t(pr$Ysoc)/h[1],t(pr$Ysur)/h[2],t(sp$data_matrices$Y))
 Xm<-rbind(t(pr$Xsoc)/h[1],t(pr$Xsur)/h[2],t(sp$data_matrices$X))
 niw<-.Call(get("_bsvarSIGNs_niw_cpp",asNamespace("bsvarSIGNs")),Ym,Xm,t(pr$A),pm,diag(psi),as.integer(pr$nu))
 M<-niw[[1]];V<-niw[[2]];R2<-unlist(lapply(0:5,function(j)5:10+10*j));q<-length(R2)
 V22<-V[R2,R2];M2<-M[R2,1:4];C<-crossprod(M2,solve(V22,M2))
 raw<-readRDS(file.path(out,sprintf("pilot_none_w%03d_s2500.rds",i)))$raw
 logw<-vapply(seq_along(raw$w),function(s){s11<-raw$Sigma[1:4,1:4,s];-.5*(q*4*log(2*pi)+4*as.numeric(determinant(V22,logarithm=TRUE)$modulus)+q*as.numeric(determinant(s11,logarithm=TRUE)$modulus)+sum(C*solve(s11)))},numeric(1))
 stopifnot(max(abs(log(raw$w)-logw))<1e-7)
 rows[[as.character(i)]]<-tibble(fold=i,restricted_coefficients=4*q,max_logweight_reconstruction_error=max(abs(log(raw$w)-logw)),min_raw_weight=min(raw$w),max_raw_weight=max(raw$w),lambda=h[3],mu=h[1],delta=h[2],psi_min=min(psi),psi_max=max(psi))
}
write_csv(bind_rows(rows),file.path(out,"weight_formula_check.csv"));print(bind_rows(rows))
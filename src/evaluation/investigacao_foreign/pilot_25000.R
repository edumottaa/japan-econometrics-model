source("C:/Users/dudup/OneDrive/japan-econometrics-model/src/evaluation/comparacao_cv_3_6/common.R")
old_dir<-file.path(root,"data/processed/cv_comparacao_20261017_193604")
out<-file.path(root,"data/processed/investigacao_foreign_20261018")
data<-readRDS(file.path(old_dir,"data_frozen.rds"));cfg<-readRDS(file.path(old_dir,"config.rds"))
trace("importance_sampling",where=asNamespace("bsvarSIGNs"),tracer=quote(assign(".pilot_raw",list(w=posterior$posterior$w,Sigma=posterior$posterior$Sigma,hyper=posterior$posterior$hyper),envir=.GlobalEnv)),print=FALSE)
rows<-list()
for(i in c(26L,27L)){
 train<-data |> slice_head(n=cfg$origins[i]);Y<-as.matrix(select(as_tibble(train),all_of(vars)))
 set.seed(cfg$seed+i)
 sp<-specify_bsvarSIGN$new(data=Y[,5:10],foreign=Y[,1:4],p=6,sign_structural=matrix(NA_real_,10,10),hyper_mu=FALSE,hyper_delta=FALSE,hyper_lambda=FALSE,hyper_psi=FALSE,mc.cores=1)
 log_line("PILOTO25000 inicio",i);start<-Sys.time()
 po<-bsvars::estimate(sp,S=25000,show_progress=FALSE)
 di<-diagnostico_signs(po,.pilot_raw$w,6,i)
 elapsed<-as.numeric(difftime(Sys.time(),start,units="secs"))
 # As 2500 primeiras amostras reponderadas mantem a mesma quantidade de caminhos da bateria original.
 small<-list(posterior=list(A=po$posterior$A[,,1:2500,drop=FALSE],Sigma=po$posterior$Sigma[,,1:2500,drop=FALSE]),last_draw=list(p=6))
 set.seed(100000+i);F12<-prever_bsvarsigns(small,Y,12)
 set.seed(300000+i);F24<-prever_bsvarsigns(small,Y,24)
 saveRDS(list(diagnostic=di,raw=.pilot_raw,posterior=small,forecast12=F12,forecast24=F24,elapsed=elapsed,seed=cfg$seed+i),file.path(out,sprintf("pilot_none_w%03d_s25000.rds",i)))
 rows[[as.character(i)]]<-di |> mutate(seconds=elapsed)
 print(di);log_line("PILOTO25000 fim",i,"segundos",elapsed)
 rm(po,small,F12,F24,.pilot_raw);gc()
}
write_csv(bind_rows(rows),file.path(out,"pilot_25000.csv"))
source("C:/Users/dudup/OneDrive/japan-econometrics-model/src/evaluation/comparacao_cv_3_6/common.R")
old_dir <- file.path(root,"data/processed/cv_comparacao_20261017_193604")
out <- file.path(root,"data/processed/investigacao_foreign_20261018")
dir.create(out,showWarnings=FALSE)
data <- readRDS(file.path(old_dir,"data_frozen.rds")); cfg <- readRDS(file.path(old_dir,"config.rds"))
trace("importance_sampling",where=asNamespace("bsvarSIGNs"),tracer=quote(assign(".pilot_raw",list(w=posterior$posterior$w,A=posterior$posterior$A,Sigma=posterior$posterior$Sigma,Theta0=posterior$posterior$Theta0,hyper=posterior$posterior$hyper),envir=.GlobalEnv)),print=FALSE)
rows <- list()
for(i in c(26L,27L)){
 train <- data |> slice_head(n=cfg$origins[i]); test <- data |> slice((cfg$origins[i]+1):min(cfg$origins[i]+12,nrow(data)))
 Y <- as.matrix(select(as_tibble(train),all_of(vars)))
 set.seed(cfg$seed+i)
 sp <- specify_bsvarSIGN$new(data=Y[,5:10],foreign=Y[,1:4],p=6,
   sign_structural=matrix(NA_real_,10,10),
   hyper_mu=FALSE,hyper_delta=FALSE,hyper_lambda=FALSE,hyper_psi=FALSE,mc.cores=1)
 log_line("PILOTO inicio",i); start<-Sys.time()
 po <- bsvars::estimate(sp,S=2500,show_progress=FALSE)
 elapsed<-as.numeric(difftime(Sys.time(),start,units="secs"))
 di<-diagnostico_signs(po,.pilot_raw$w,6,i)
 set.seed(100000+i); F<-prever_bsvarsigns(po,Y,12)
 sc<-score_draws(F,train,test,i,"foreign_p6_sem_normalizacao",di$quality)
 raw<-.pilot_raw; saveRDS(list(diagnostic=di,scores=sc,raw=raw,forecast=F,elapsed=elapsed,seed=cfg$seed+i),file.path(out,sprintf("pilot_none_w%03d_s2500.rds",i)))
 rows[[as.character(i)]]<-di |> mutate(seconds=elapsed)
 print(di);log_line("PILOTO fim",i,"segundos",elapsed)
 rm(po,F,raw,.pilot_raw);gc()
}
write_csv(bind_rows(rows),file.path(out,"pilot_normalizacao.csv"))